"""The 2D stage written as a program: text that animates, a chart, a layout, a
path that draws itself and nodes joined by a connector -- built from data.

What it shows:
- styles tokens and `var(--name)`: the colours are the film's tokens, never
  literals in the shapes, so a palette change re-colours everything;
- a text asset with a `textAnimator` preset, and a counter;
- a chart asset whose values come from a Python list and whose `progress` is keyed;
- a `group` with `layout="row"` that places explicit children, generated by a loop;
- a path with `trimEnd` keyed so it draws itself, and a `connector` between nodes.

Every label, value and colour is a placeholder for what your own film says.
"""
from srkit import FRAME, S, save

DURATION = 6.0
VALUES = [12, 30, 21, 44]                     # the data the chart and the cards show
LABELS = ["A", "B", "C", "D"]

scene = S.Scene(version="auto")
scene.add_project(width=FRAME["width"], height=FRAME["height"], fps=str(FRAME["fps"]),
                  duration=DURATION, background="var(--background)")
styles = scene.add_styles()
for name, value in (("background", "#14181E"), ("ink", "#EEF1F4"), ("accent", "#46C2E8"),
                    ("muted", "#7D8898")):
    styles.add_token(name=name, value=value)

assets = scene.add_assets()
assets.add_text(id="t-title", text="Four values", width=1200, height=140, size=72,
                color="var(--ink)", align="center")
assets.add_text(id="t-total", text=str(sum(VALUES)), width=600, height=160, size=120,
                color="var(--accent)", align="center")
chart = assets.add_chart(id="c-values", kind="column", width=900, height=420,
                         labels=",".join(LABELS), showValues=True)
chart.add_series(name="values", values=" ".join(map(str, VALUES)), color="var(--accent)")
progress = chart.add_animate(property="progress")
progress.add_key(time="0.5", value="0")
progress.add_key(time="2", value="1", interpolation="ease-out")

stage = scene.add_symbols().add_symbol(id="stage", width=FRAME["width"],
                                       height=FRAME["height"], duration=DURATION)
stage.add_layer(id="l-title", asset="t-title", x=360, y=60).add_textAnimator(
    preset="word-by-word", presetStart=0.2, presetDuration=1.0, presetEase="cubic-out")
stage.add_layer(id="l-chart", asset="c-values", x=120, y=300)
stage.add_layer(id="l-total", asset="t-total", x=1240, y=320).add_textAnimator(
    preset="counter", presetStart=1, presetDuration=2)

cards = stage.add_group(id="cards", layout="row", gap=40, justify="center",
                        alignItems="end", x=1040, y=480, width=760, height=220)
top = max(VALUES)
for label, value in zip(LABELS, VALUES):
    card = cards.add_shape(id=f"card-{label.lower()}", shape="rounded-rect", width=140,
                           height=round(200 * value / top), radius=14,
                           fill="var(--accent)" if value == top else "var(--muted)")
    fade = card.add_animate(property="opacity")
    fade.add_key(time="2", value="0")
    fade.add_key(time="2.6", value="1", interpolation="ease-out")

# an open path needs its box (width/height) and a transparent fill
arrow = stage.add_shape(id="arrow", shape="path", path="M 980 260 L 1240 380", width=260,
                        height=120, stroke="var(--ink)", strokeWidth=5, markerEnd="arrow",
                        fill="#00000000", trimEnd=0)
draw = arrow.add_animate(property="trimEnd")
draw.add_key(time="2.5", value="0")
draw.add_key(time="3.3", value="1", interpolation="ease-out")

nodes = stage.add_group(id="nodes")
# nothing but captions may enter rows 820-1080 of a 1080 frame
nodes.add_shape(id="n-from", shape="ellipse", x=1300, y=730, width=60, height=60,
                fill="var(--accent)")
nodes.add_shape(id="n-to", shape="ellipse", x=1700, y=730, width=60, height=60,
                fill="var(--muted)")
nodes.add_connector(id="n-link", from_="n-from", to="n-to", stroke="var(--ink)",
                    markerEnd="arrow")

scene.add_composition().add_instance(id="use-stage", symbol="stage", start=0, end=DURATION)
save(scene, "stage_2d.scene.xml")
